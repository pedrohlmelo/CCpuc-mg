def documento(linha, materia_do_assunto):
    qid, assunto, dificuldade, enunciado, explicacao, gabarito, textos, imagem, descricao, figuras = linha
    treino = qid <= ULTIMA_DE_TREINO
    figuras = figuras or [(None, None)] * len(textos)
    return {
        "id": qid, "materia": materia_do_assunto.get(assunto), "assunto": assunto,
        "dificuldade": dificuldade, "dificuldade_irt": None, "enunciado": enunciado,
        "explicacao": explicacao, "imagem": imagem, "imagem_descricao": descricao,
        "fonte": FONTE, "explicacao_gerada": not treino, "revisado": treino, "ativo": True,
        "confianca_classificacao": None,
        "alternativas": [
            {"letra": l, "texto": t, "correta": l == gabarito,
             "imagem": f[0], "imagem_descricao": f[1]}
            for l, t, f in zip("ABCDE", textos, figuras)
        ],
    }


def main():
    args = argparse.ArgumentParser()
    args.add_argument("--simular", action="store_true")
    args = args.parse_args()

    db = comum.conectar(args.simular)
    _, materia_do_assunto, _ = comum.ler_estrutura(db)
    existentes = comum.ler_questoes(db)
    relogio = comum.Relogio()
    novas = {}
    for linha in AUTORAIS:
        if linha[0] not in existentes:
            doc = documento(linha, materia_do_assunto)
            assert comum.alternativas_validas(doc["alternativas"]), linha[0]
            novas[linha[0]] = {**doc, "atualizado_em": relogio.proximo()}
    comum.gravar_lotes(db, "questoes", novas, args.simular)
    print(f"{len(novas)} autorais novas, {len(AUTORAIS) - len(novas)} já existiam")
    if novas:
        comum.subir_versao(db, relogio, args.simular)


if __name__ == "__main__":
    main()
